create or replace function public.v5_4_editar_guia(
  p_guia_id bigint,
  p_usuario_id text,
  p_perfil_id bigint,
  p_numero text,
  p_data_guia date,
  p_om_origem text,
  p_om_destino text,
  p_assunto text,
  p_deposito_destino text
)
returns void
language plpgsql
as $$
declare
  g public.guias_orcamentarias%rowtype;
  novo_deposito text;
begin
  select * into g
  from public.guias_orcamentarias
  where id=p_guia_id
  for update;

  if not found then raise exception 'Guia não encontrada.'; end if;

  if not public.v5_4_pode_gerenciar(p_usuario_id,p_perfil_id,g.criado_por) then
    raise exception 'Somente o criador da guia ou um Admin pode editá-la.';
  end if;

  if nullif(trim(coalesce(p_numero,'')),'') is null
     or p_data_guia is null
     or nullif(trim(coalesce(p_om_origem,'')),'') is null
     or nullif(trim(coalesce(p_om_destino,'')),'') is null
     or nullif(trim(coalesce(p_assunto,'')),'') is null then
    raise exception 'Preencha todos os campos obrigatórios.';
  end if;

  if g.tipo in ('transferencia','remessa') then
    if nullif(trim(coalesce(p_deposito_destino,'')),'') is null then
      raise exception 'Informe o depósito de destino.';
    end if;
    if not exists(
      select 1 from public.orc_depositos d
      where d.ativo=true and d.nome=p_deposito_destino
    ) then
      raise exception 'Depósito de destino inválido.';
    end if;
    novo_deposito := p_deposito_destino;
  else
    novo_deposito := null;
  end if;

  update public.guias_orcamentarias
  set numero=trim(p_numero),
      data_guia=p_data_guia,
      om_origem=trim(p_om_origem),
      om_destino=trim(p_om_destino),
      assunto=trim(p_assunto),
      deposito_destino=novo_deposito
  where id=p_guia_id;

  insert into public.guia_tramitacoes(
    guia_id,evento,mensagem,usuario_id,perfil_id
  ) values (
    p_guia_id,
    'guia_editada',
    'Dados cadastrais da guia foram editados.',
    p_usuario_id,
    p_perfil_id
  );
end;
$$;

create or replace function public.v5_4_excluir_guia(
  p_guia_id bigint,
  p_usuario_id text,
  p_perfil_id bigint
)
returns text[]
language plpgsql
as $$
declare
  g public.guias_orcamentarias%rowtype;
  paths text[];
  snap jsonb;
begin
  select * into g
  from public.guias_orcamentarias
  where id=p_guia_id
  for update;

  if not found then raise exception 'Guia não encontrada.'; end if;

  if not public.v5_4_pode_gerenciar(p_usuario_id,p_perfil_id,g.criado_por) then
    raise exception 'Somente o criador da guia ou um Admin pode excluí-la.';
  end if;

  select coalesce(array_agg(a.arquivo_path order by a.id),array[]::text[])
    into paths
    from public.guia_anexos a
   where a.guia_id=p_guia_id;

  select to_jsonb(g) || jsonb_build_object(
    'anexos',coalesce((
      select jsonb_agg(to_jsonb(a) order by a.id)
      from public.guia_anexos a where a.guia_id=p_guia_id
    ),'[]'::jsonb),
    'historico',coalesce((
      select jsonb_agg(to_jsonb(t) order by t.id)
      from public.guia_tramitacoes t where t.guia_id=p_guia_id
    ),'[]'::jsonb)
  ) into snap;

  insert into public.orcamentarios_exclusoes(
    entidade,entidade_id,identificador,snapshot,
    excluido_por,excluido_por_perfil_id
  ) values (
    'guia',p_guia_id::text,g.numero,snap,
    p_usuario_id,p_perfil_id
  );

  delete from public.guias_orcamentarias where id=p_guia_id;
  return paths;
end;
$$;


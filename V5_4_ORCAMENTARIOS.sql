create table if not exists public.movimentacoes_material (
  id bigint generated by default as identity primary key,
  numero text not null,
  data_movimentacao date not null default current_date,

  dependencia_origem text not null,
  dependencia_destino text not null,

  finalidade text not null,
  observacoes text null,

  valor_total numeric(16,2) not null default 0,

  criado_por text not null,
  criado_por_perfil_id bigint null
    references public.usuario_perfis(id) on delete set null,
  secao_criador text null,
  posicao_criador text null,

  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists idx_mov_material_data
  on public.movimentacoes_material(data_movimentacao desc,id desc);

create table if not exists public.movimentacao_material_itens (
  id bigint generated by default as identity primary key,
  movimentacao_id bigint not null
    references public.movimentacoes_material(id) on delete cascade,

  nome text not null,
  numero_ficha text not null,
  quantidade numeric(14,3) not null check (quantidade>0),
  valor_unitario numeric(16,2) not null check (valor_unitario>=0),

  valor_total numeric(18,2)
    generated always as (round(quantidade*valor_unitario,2)) stored,

  criado_em timestamptz not null default now()
);

create index if not exists idx_mov_material_itens
  on public.movimentacao_material_itens(movimentacao_id,id);

create table if not exists public.movimentacao_material_anexos (
  id bigint generated by default as identity primary key,
  movimentacao_id bigint not null
    references public.movimentacoes_material(id) on delete cascade,

  arquivo_nome text not null,
  arquivo_path text not null,
  arquivo_url text not null,
  arquivo_mime text null,
  arquivo_tamanho bigint null,
  observacao text null,

  enviado_por text not null,
  enviado_por_perfil_id bigint null
    references public.usuario_perfis(id) on delete set null,

  criado_em timestamptz not null default now()
);

create index if not exists idx_mov_material_anexos
  on public.movimentacao_material_anexos(movimentacao_id,criado_em desc,id desc);

create table if not exists public.movimentacao_material_tramitacoes (
  id bigint generated by default as identity primary key,
  movimentacao_id bigint not null
    references public.movimentacoes_material(id) on delete cascade,

  evento text not null,
  mensagem text null,

  usuario_id text not null,
  perfil_id bigint null
    references public.usuario_perfis(id) on delete set null,

  criado_em timestamptz not null default now()
);

create index if not exists idx_mov_material_tramitacoes
  on public.movimentacao_material_tramitacoes(movimentacao_id,criado_em desc,id desc);


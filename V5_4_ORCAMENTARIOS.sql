-- ---------------------------------------------------------------------
-- Pode gerenciar: criador ou Admin ativo.
-- ---------------------------------------------------------------------
create or replace function public.v5_4_pode_gerenciar(
  p_usuario_id text,
  p_perfil_id bigint,
  p_criado_por text
)
returns boolean
language sql
stable
as $$
  select
    p_usuario_id = p_criado_por
    or exists (
      select 1
      from public.usuario_perfis p
      where p.id = p_perfil_id
        and p.usuario_id::text = p_usuario_id
        and p.ativo = true
        and lower(trim(p.secao)) = 'admin'
    );
$$;


-- TAREFAS V7.7.0 — conferência, validade e pendências do Material Carga / Depósitos

alter table public.orc_documentos_carga
  add column if not exists conferido_por text,
  add column if not exists conferido_em timestamptz,
  add column if not exists motivo_atualizacao text;

update public.orc_documentos_carga
set conferido_por = coalesce(conferido_por, atualizado_por),
    conferido_em = coalesce(conferido_em, criado_em),
    motivo_atualizacao = coalesce(motivo_atualizacao, 'historico')
where conferido_por is null or conferido_em is null or motivo_atualizacao is null;

alter table public.orc_documentos_carga
  alter column conferido_por set not null,
  alter column conferido_em set default now(),
  alter column conferido_em set not null,
  alter column motivo_atualizacao set default 'manual',
  alter column motivo_atualizacao set not null;

create table if not exists public.orc_carga_pendencias (
  id bigint generated by default as identity primary key,
  tipo_referencia text not null check (tipo_referencia in ('dependencia','deposito')),
  referencia text not null,
  origem_tipo text not null,
  origem_id bigint,
  origem_numero text,
  descricao text,
  status text not null default 'pendente' check (status in ('pendente','resolvida')),
  criada_em timestamptz not null default now(),
  resolvida_em timestamptz,
  resolvida_documento_id bigint references public.orc_documentos_carga(id) on delete set null
);

create index if not exists orc_carga_pendencias_abertas_idx
  on public.orc_carga_pendencias(tipo_referencia, referencia, criada_em desc)
  where status='pendente';

create unique index if not exists orc_carga_pendencias_origem_unq
  on public.orc_carga_pendencias(tipo_referencia, referencia, origem_tipo, origem_id)
  where status='pendente' and origem_id is not null;

alter table public.orc_carga_pendencias enable row level security;
drop policy if exists "orc_carga_pendencias_select_anon" on public.orc_carga_pendencias;
create policy "orc_carga_pendencias_select_anon" on public.orc_carga_pendencias for select to anon using (true);
drop policy if exists "orc_carga_pendencias_select_authenticated" on public.orc_carga_pendencias;
create policy "orc_carga_pendencias_select_authenticated" on public.orc_carga_pendencias for select to authenticated using (true);
grant select on public.orc_carga_pendencias to anon, authenticated;
revoke insert, update, delete, truncate on public.orc_carga_pendencias from anon, authenticated;

create or replace function public.v7_7_0_criar_pendencia_carga(
  p_tipo_referencia text,p_referencia text,p_origem_tipo text,p_origem_id bigint,
  p_origem_numero text,p_descricao text default null
) returns void language plpgsql security definer set search_path=public as $$
begin
  if p_tipo_referencia not in ('dependencia','deposito') or nullif(trim(coalesce(p_referencia,'')),'') is null then return; end if;
  if p_origem_id is not null and exists (
    select 1 from public.orc_carga_pendencias where tipo_referencia=p_tipo_referencia and referencia=p_referencia
      and origem_tipo=p_origem_tipo and origem_id=p_origem_id and status='pendente'
  ) then return; end if;
  insert into public.orc_carga_pendencias(tipo_referencia,referencia,origem_tipo,origem_id,origem_numero,descricao)
  values(p_tipo_referencia,p_referencia,p_origem_tipo,p_origem_id,p_origem_numero,p_descricao);
end;$$;
revoke all on function public.v7_7_0_criar_pendencia_carga(text,text,text,bigint,text,text) from public, anon, authenticated;

create or replace function public.v7_7_0_pedido_carga_trigger() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if new.status='pronto' and old.status is distinct from new.status then
    if new.tipo='desrelacionamento_baixa' then
      if new.categoria='consumo' then
        perform public.v7_7_0_criar_pendencia_carga('deposito',new.deposito_origem,'desrelacionamento',new.id,new.numero,'Desrelacionamento/Baixa concluído: atualizar a relação do depósito.');
      else
        perform public.v7_7_0_criar_pendencia_carga('dependencia',new.dependencia_origem,'desrelacionamento',new.id,new.numero,'Desrelacionamento/Baixa concluído: gerar e anexar nova relação de carga da dependência.');
      end if;
    elsif new.tipo='distribuicao' then
      if new.deposito_origem is not null then
        perform public.v7_7_0_criar_pendencia_carga('deposito',new.deposito_origem,'distribuicao',new.id,new.numero,'Distribuição concluída: atualizar a relação do depósito de origem.');
      end if;
      if new.dependencia_destino is not null then
        perform public.v7_7_0_criar_pendencia_carga('dependencia',new.dependencia_destino,'distribuicao',new.id,new.numero,'Distribuição concluída: gerar e anexar nova relação de carga da dependência de destino.');
      end if;
    end if;
  end if;
  return new;
end;$$;
revoke all on function public.v7_7_0_pedido_carga_trigger() from public, anon, authenticated;
drop trigger if exists trg_v7_7_0_pedido_carga on public.pedidos_orcamentarios;
create trigger trg_v7_7_0_pedido_carga after update of status on public.pedidos_orcamentarios
for each row execute function public.v7_7_0_pedido_carga_trigger();


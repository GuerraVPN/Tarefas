create or replace function public.v7_7_0_registrar_documento_carga(
  p_tipo_referencia text,p_referencia text,p_arquivo_nome text,p_arquivo_path text,p_arquivo_url text,
  p_arquivo_mime text,p_arquivo_tamanho bigint,p_usuario_id text,p_perfil_id bigint,p_conferido_por text,
  p_observacao text default null,p_motivo_atualizacao text default 'manual'
) returns bigint language plpgsql security definer set search_path=public as $$
declare v_versao integer; v_id bigint;
begin
  if not public.v5_eh_fiscalizacao(p_usuario_id,p_perfil_id) then raise exception 'Somente a Fiscalização pode atualizar Material Carga/Depósito.'; end if;
  if nullif(trim(coalesce(p_conferido_por,'')),'') is null or not exists(select 1 from public.usuarios u where u.id::text=p_conferido_por) then raise exception 'Informe quem conferiu a relação.'; end if;
  if p_tipo_referencia='dependencia' then
    if not exists(select 1 from public.orc_dependencias d where d.ativo=true and d.nome=p_referencia) then raise exception 'Dependência inválida.'; end if;
  elsif p_tipo_referencia='deposito' then
    if not exists(select 1 from public.orc_depositos d where d.ativo=true and d.nome=p_referencia) then raise exception 'Depósito inválido.'; end if;
  else raise exception 'Tipo de referência inválido.'; end if;

  select coalesce(max(versao),0)+1 into v_versao from public.orc_documentos_carga where tipo_referencia=p_tipo_referencia and referencia=p_referencia;
  insert into public.orc_documentos_carga(tipo_referencia,referencia,versao,arquivo_nome,arquivo_path,arquivo_url,arquivo_mime,arquivo_tamanho,observacao,atualizado_por,atualizado_por_perfil_id,conferido_por,conferido_em,motivo_atualizacao)
  values(p_tipo_referencia,p_referencia,v_versao,p_arquivo_nome,p_arquivo_path,p_arquivo_url,p_arquivo_mime,p_arquivo_tamanho,p_observacao,p_usuario_id,p_perfil_id,p_conferido_por,now(),coalesce(nullif(trim(p_motivo_atualizacao),''),'manual')) returning id into v_id;
  update public.orc_carga_pendencias set status='resolvida',resolvida_em=now(),resolvida_documento_id=v_id where tipo_referencia=p_tipo_referencia and referencia=p_referencia and status='pendente';
  return v_id;
end;$$;
revoke all on function public.v7_7_0_registrar_documento_carga(text,text,text,text,text,text,bigint,text,bigint,text,text,text) from public;
grant execute on function public.v7_7_0_registrar_documento_carga(text,text,text,text,text,text,bigint,text,bigint,text,text,text) to anon, authenticated;